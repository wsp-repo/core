import { Type } from '@sinclair/typebox';
import { describe, it, expect } from 'vitest';

import { TypeboxValidator } from '../../validator';

import { TFormats } from '../../types';

const ipv4Validator = new TypeboxValidator(
  Type.String({ format: TFormats.Ipv4 }),
);

describe('Typebox', () => {
  describe('TFormats.Ipv4', () => {
    describe('valid IPv4 addresses', () => {
      it.each([
        '0.0.0.0',
        '127.0.0.1',
        '192.168.1.1',
        '10.0.0.1',
        '172.16.0.1',
        '255.255.255.255',
        '1.1.1.1',
        '8.8.8.8',
        '208.67.222.222',
        '203.0.113.1',
        '198.51.100.1',
        '192.0.2.1',
        '169.254.1.1',
        '224.0.0.1',
        '239.255.255.255',
        '192.168.0.255',
        '10.255.255.255',
        '172.31.255.255',
        '127.255.255.254',
        '10.0.0.0',
        '10.255.255.255',
        '172.16.0.0',
        '172.31.255.255',
        '192.168.0.0',
        '192.168.255.255',
        '169.254.0.0',
        '169.254.255.255',
        '0.1.1.1',
        '1.0.1.1',
        '1.1.0.1',
        '1.1.1.0',
      ])('should validate IPv4 address: %s', (ipv4) => {
        expect(() => ipv4Validator.compile(ipv4)).not.toThrow();
        expect(ipv4Validator.compile(ipv4)).toBe(ipv4);
      });
    });

    describe('invalid IPv4 addresses', () => {
      it.each([
        '256.1.1.1',
        '1.256.1.1',
        '1.1.256.1',
        '1.1.1.256',
        '300.300.300.300',
        '192.168.1',
        '192.168',
        '192',
        '192.168.1.1.1',
        '192.168.01.1',
        '192.168.001.1',
        '01.1.1.1',
        '192.168.1.01',
        '',
        'not-an-ip',
        '192.168.1.',
        '.192.168.1.1',
        '192..168.1.1',
        '192.168.-1.1',
        '192.168.1.-1',
        '-1.1.1.1',
        '192.168.1.1.',
        '192.168.1.1a',
        'a192.168.1.1',
        '192.168.a.1',
        '192 168 1 1',
        '192,168,1,1',
        '192:168:1:1',
        '999.999.999.999',
        '1.1.1',
        '1.1.1.1.1.1',
        '192.168.1.1/24',
        '192.168.1.1:80',
        '256.0.0.1',
        '0.256.0.1',
        '0.0.256.1',
        '0.0.0.256',
        '001.1.1.1',
      ])('should reject IPv4 address: %s', (ipv4) => {
        expect(() => ipv4Validator.compile(ipv4)).toThrow();
      });
    });
  });
});
